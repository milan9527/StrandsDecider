"""Render the comparison report's payment flow as SVG and PNG, without Mermaid."""

import argparse
from xml.etree import ElementTree as ET

from generate_diagrams import OUT, Page


def diagram(english=False):
    if english:
        title = "Payment support: decisions and execution"
        subtitle = "Each model uses the same initial snapshot for five independent decisions."
        labels = [
            "Original facts\nAmount\nConfirmations\nApproval / payout",
            "Five independent decisions\nIntake · Verify · Approve\nProcess · Close",
            "Save original\nfive choices",
            "Execute suggestions\nSimulated executor\nFunds guards",
            "Final outcome\nFunds state\nTicket state\nCustomer reply",
        ]
        footer = "Preserve model choices separately from guarded execution results."
    else:
        title = "支付客服：固定快照决策与模拟执行"
        subtitle = "每个模型使用同一份初始业务快照，完成五次独立判断。"
        labels = [
            "原始业务快照\n金额、确认数\n审批与结算状态",
            "五次独立判断\n受理 · 核验 · 审批\n处置 · 结案",
            "保留五个\n模型原始选择",
            "执行建议\n模拟执行器\n资金保护",
            "最终结果\n资金状态\n工单状态\n客服回复",
        ]
        footer = "模型原始选择与保护后的实际执行结果分别保留。"
    page = Page(
        title, "five-model-payment-flow." + ("en" if english else "zh"),
        subtitle, width=1600, height=460,
    )
    page.nodes[1]["size"] = 22
    positions = [(40, 210), (290, 380), (710, 220), (970, 300), (1310, 250)]
    for i, ((x, width), label, palette) in enumerate(
        zip(positions, labels, ["gray", "blue", "purple", "orange", "teal"])
    ):
        page.box(f"step-{i}", x, 150, width, 240, label, palette=palette, size=24)
        if i:
            prev_x, prev_width = positions[i - 1]
            page.edge(
                f"step-{i - 1}", f"step-{i}",
                [(prev_x + prev_width, 270), (x, 270)],
            )
    page.box("footer", 40, 405, 1520, 35, footer, size=21, text=True)
    return page


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--chromium", help="Optional Playwright Chromium executable path")
    args = parser.parse_args()
    from playwright.sync_api import sync_playwright

    OUT.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as pw:
        options = {"executable_path": args.chromium} if args.chromium else {}
        browser = pw.chromium.launch(headless=True, args=["--no-sandbox"], **options)
        page = browser.new_page(viewport={"width": 1600, "height": 460}, device_scale_factor=2)
        for english in (False, True):
            chart = diagram(english)
            svg = chart.svg()
            svg.find("desc").text = "Generated by scripts/generate_comparison_flowcharts.py"
            ET.indent(svg)
            path = OUT / f"{chart.slug}.svg"
            ET.ElementTree(svg).write(path, encoding="utf-8", xml_declaration=True)
            page.goto(path.resolve().as_uri())
            page.evaluate("document.fonts.ready")
            page.locator("svg").screenshot(path=str(OUT / f"{chart.slug}.png"))
            print(chart.slug)
        browser.close()


if __name__ == "__main__":
    main()
