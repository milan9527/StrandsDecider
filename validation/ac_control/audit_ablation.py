"""Final evidence audit and optional cleanup of this run's private transfer objects."""

import argparse
import hashlib
import io
import json
import tarfile
from pathlib import Path

import boto3
from ablation_protocol import gate_payload, make_payload
from analyze_ablation import analyze
from compare_resident import MODEL_IDS
from prepare import save, sha

HERE = Path(__file__).resolve().parent


def service_properties(text):
    result = {}
    for block in text.strip().split("\n\n"):
        properties = dict(line.split("=", 1) for line in block.splitlines() if "=" in line)
        if properties:
            result[properties["Id"]] = properties
    return result


def audit(run, cleanup=False):
    plan = json.loads((run / "plan.json").read_text())
    experiments = json.loads((run / "experiments.json").read_text())
    refs = {r["id"]: r for r in json.loads((run / "references.json").read_text())}
    cap = json.loads((run / "command_set.json").read_text())
    for name, checksum in plan["source_sha256"].items():
        assert hashlib.sha256((HERE / name).read_bytes()).hexdigest() == checksum, name
    lookup = {(e["case_id"], e["variant"], e["arm"]): e for e in experiments}
    for e in experiments:
        state = json.loads(e["first_payload"]["state"])
        assert state["query"] == refs[e["case_id"]]["query"]
        assert state["commandSet"] == cap["commandSet"]
        assert len(e["first_payload"]["questions"]) == 30
        base = lookup[e["case_id"], e["variant"], "baseline"]["first_payload"]
        candidate = make_payload(base, e["arm"])
        if e["arm"] == "two_stage":
            assert sha(candidate) == e["value_sha256"]
            candidate = gate_payload(candidate, e["variant"] == "reversed")
        assert sha(candidate) == e["first_sha256"]
    historical = json.loads((HERE / "runs/2026-10-30-v1/references.json").read_text())
    assert all(refs[r["id"]]["expected"] == r["expected"] and
               refs[r["id"]]["query"] == r["query"] for r in historical)
    result, rows = analyze(run)
    assert len(rows) == plan["observations_per_model"] * 3
    for provider, model in MODEL_IDS.items():
        for phase in ("before", "after"):
            health = json.loads((run / provider / f"formal_health_{phase}.json").read_text())
            assert health["status"] == "ok"
            body = health["response"]
            assert body["model"] == model
            assert body.get("status") == "ok" or body.get("ok") is True
    services = []
    for phase in ("formal_before", "formal_after"):
        snapshot = json.loads((run / (phase + "_environment.json")).read_text())
        assert snapshot["services"]["returncode"] == 0
        services.append(service_properties(snapshot["services"]["stdout"]))
    assert set(services[0]) == set(services[1])
    for key in services[0]:
        before, after = services[0][key], services[1][key]
        assert before["ActiveState"] == after["ActiveState"] == "active"
        assert before["NRestarts"] == after["NRestarts"]
        assert before["ExecMainStartTimestamp"] == after["ExecMainStartTimestamp"]
    ssm = json.loads((run / "formal_ssm.json").read_text())
    assert ssm["Status"] == "Success" and ssm["ResponseCode"] == 0
    audit_result = {
        "frozen_experiments": len(experiments), "observations": len(rows),
        "new_http_calls": result["new_http_calls"],
        "errors": sum(r["status"] != "ok" for r in rows),
        "checks": [
            "Frozen/current source hashes match",
            "All queries and full capability sets preserved",
            "Factors regenerated byte-for-byte including candidate ordering",
            "Original specification references unchanged",
            "Every actual payload and parsed response audited against frozen inputs/raw HTTP",
            "Second-stage keys selected only by recorded model gates",
            "Historical baseline file hashes unchanged",
            "Full formal observation count and no duplicate or missing experiment",
            "SSM successful; services active with unchanged restart counts/start timestamps",
            "All three model identities and health valid before and after formal calls",
        ],
        "receipts_sha256": result["receipts_sha256"],
        "scored_results_sha256": hashlib.sha256((run / "ablation_results.json").read_bytes()).hexdigest(),
    }
    if cleanup:
        transfer = json.loads((run / "transfer.json").read_text())
        s3 = boto3.client("s3", region_name=transfer["region"])
        input_key = "input/" + transfer["prefix"] + "/input.tar.gz"
        content = s3.get_object(Bucket=transfer["bucket"], Key=input_key)["Body"].read()
        assert hashlib.sha256(content).hexdigest() == transfer["input_archive_sha256"]
        with tarfile.open(fileobj=io.BytesIO(content), mode="r:gz") as archive:
            assert set(archive.getnames()) == set(transfer["transferred_files"])
            assert not any("reference" in name for name in archive.getnames())
            for member in archive.getmembers():
                source = run / member.name if member.name.endswith(".json") else run / "sources" / member.name
                assert archive.extractfile(member).read() == source.read_bytes()
        keys = [input_key]
        prefix = "output/" + transfer["prefix"] + "/results/"
        checksums = {}
        for page in s3.get_paginator("list_objects_v2").paginate(Bucket=transfer["bucket"], Prefix=prefix):
            for item in page.get("Contents", []):
                relative = Path(item["Key"].removeprefix(prefix))
                assert not relative.is_absolute() and ".." not in relative.parts
                data = s3.get_object(Bucket=transfer["bucket"], Key=item["Key"])["Body"].read()
                assert data == (run / relative).read_bytes(), relative
                checksums[str(relative)] = hashlib.sha256(data).hexdigest()
                keys.append(item["Key"])
        response = s3.delete_objects(Bucket=transfer["bucket"],
                                     Delete={"Objects": [{"Key": k} for k in keys], "Quiet": True})
        assert not response.get("Errors")
        save(run / "transfer_cleanup.json", {
            "deleted_object_count": len(keys), "output_files_sha256": checksums,
            "input_archive_sha256": transfer["input_archive_sha256"],
            "remote_gpu_directory_retained": True,
            "note": "Only this run's exact input archive and byte-verified output objects were deleted.",
        })
        audit_result["checks"].append("Transferred package excludes references; all S3 evidence byte-verified before cleanup")
    save(run / "audit.json", audit_result)
    print(json.dumps(audit_result, ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, required=True)
    parser.add_argument("--cleanup", action="store_true")
    args = parser.parse_args()
    audit(args.run, args.cleanup)
